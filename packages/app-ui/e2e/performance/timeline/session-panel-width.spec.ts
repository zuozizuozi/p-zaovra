import { expect, test } from "@playwright/test"
import { setupTimelineBenchmark } from "./session-timeline-benchmark.fixture"

test("review divider remains draggable at a common desktop width", async ({ page }) => {
  await setupTimelineBenchmark(page, { historyTurns: 0, eventBatch: 1, newLayoutDesigns: true, git: false })
  await page.setViewportSize({ width: 1280, height: 800 })
  await page.emulateMedia({ reducedMotion: "reduce" })
  await page.getByRole("button", { name: "Toggle review", exact: true }).click()
  const handle = page.locator('[data-component="resize-handle"][data-direction="horizontal"]').first()
  await expect(handle).toBeVisible()
  const initial = await handle.boundingBox()
  if (!initial) throw new Error("Review divider has no bounds")
  await page.mouse.move(initial.x + 4, initial.y + 100)
  await page.mouse.down()
  await page.mouse.move(initial.x - 396, initial.y + 100, { steps: 12 })
  await page.mouse.up()
  const before = await handle.boundingBox()
  if (!before) throw new Error("Review divider has no bounds")
  await page.mouse.move(before.x + 4, before.y + 100)
  await page.mouse.down()
  await page.mouse.move(before.x + 124, before.y + 100, { steps: 12 })
  await page.mouse.up()
  await expect.poll(async () => (await handle.boundingBox())?.x ?? 0).toBeGreaterThan(before.x + 100)
})

test("narrow session keeps review readable through full-width tabs", async ({ page }) => {
  await setupTimelineBenchmark(page, { historyTurns: 0, eventBatch: 1, newLayoutDesigns: true, git: false })
  await page.setViewportSize({ width: 800, height: 800 })
  const session = page.getByRole("tab", { name: "Session", exact: true })
  const changes = page.getByRole("tab", { name: "Changes", exact: true })
  await expect(session).toBeVisible()
  await expect(page.locator("#review-panel")).toHaveCount(0)
  await changes.click()
  await expect(changes).toHaveAttribute("aria-selected", "true")
  await expect(page.getByRole("textbox", { name: "Prompt", exact: true })).toHaveCount(0)
  await session.click()
  await expect(page.getByRole("textbox", { name: "Prompt", exact: true })).toBeVisible()
  await page.setViewportSize({ width: 1280, height: 800 })
  await expect(session).toHaveCount(0)
})
